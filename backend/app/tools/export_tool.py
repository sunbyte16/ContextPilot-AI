import json
import csv
import io
from typing import Dict, Any, Optional
from datetime import datetime, timezone
from app.tools.base import BaseTool
from app.models.all_models import Task, Memory


class ExportTool(BaseTool):
    tool_id = "export_tool"
    name = "Data & Report Exporter"
    description = "Exports tasks, analysis summaries, and project records into structured Markdown, JSON, or CSV formats."
    version = "1.0.0"
    risk_level = "MEDIUM"
    requires_approval = True  # Explicitly requires human approval for report generation/consequential export
    implementation_type = "local"

    def get_input_schema(self) -> Dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "format": {
                    "type": "string",
                    "enum": ["markdown", "json", "csv"],
                    "default": "markdown",
                    "description": "Export document format"
                },
                "content_type": {
                    "type": "string",
                    "enum": ["tasks_summary", "analysis_report", "memories_export"],
                    "default": "tasks_summary"
                },
                "title": {
                    "type": "string",
                    "description": "Report title header"
                }
            },
            "required": ["format"]
        }

    def get_output_schema(self) -> Dict[str, Any]:
        return {
            "type": "object",
            "properties": {
                "success": {"type": "boolean"},
                "filename": {"type": "string"},
                "content": {"type": "string"},
                "format": {"type": "string"},
                "size_bytes": {"type": "integer"}
            }
        }

    def execute(self, params: Dict[str, Any], context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        export_format = params.get("format", "markdown").lower()
        content_type = params.get("content_type", "tasks_summary")
        title = params.get("title", f"ContextPilot AI Report - {content_type}")
        db = context.get("db") if context else None
        user = context.get("user") if context else None

        if not db or not user:
            raise ValueError("Database and user context required for ExportTool.")

        now_str = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        filename = f"contextpilot_{content_type}_{now_str}.{ 'md' if export_format == 'markdown' else export_format }"

        output_text = ""
        if export_format == "json":
            tasks = db.query(Task).filter(Task.user_id == user.id).limit(20).all()
            data = {
                "report_title": title,
                "exported_at": datetime.now(timezone.utc).isoformat(),
                "user_email": user.email,
                "tasks": [
                    {
                        "id": t.id,
                        "objective": t.objective,
                        "status": t.status,
                        "priority": t.priority,
                        "progress": t.progress,
                        "created_at": t.created_at.isoformat() if t.created_at else None
                    }
                    for t in tasks
                ]
            }
            output_text = json.dumps(data, indent=2)

        elif export_format == "csv":
            tasks = db.query(Task).filter(Task.user_id == user.id).limit(50).all()
            sio = io.StringIO()
            writer = csv.writer(sio)
            writer.writerow(["Task ID", "Objective", "Status", "Priority", "Progress", "Created At"])
            for t in tasks:
                writer.writerow([t.id, t.objective, t.status, t.priority, t.progress, t.created_at])
            output_text = sio.getvalue()

        else:  # markdown default
            tasks = db.query(Task).filter(Task.user_id == user.id).limit(10).all()
            lines = [
                f"# {title}",
                f"*Generated by ContextPilot AI on {datetime.now(timezone.utc).strftime('%B %d, %Y at %H:%M UTC')}*",
                f"*User: {user.email}*",
                "",
                "## Summary Overview",
                f"- Total Recorded Tasks: {len(tasks)}",
                f"- User Workspace: Authenticated Active Tenant",
                "",
                "## Tasks Ledger",
                "| Task Objective | Status | Priority | Progress |",
                "| :--- | :--- | :--- | :--- |",
            ]
            for t in tasks:
                lines.append(f"| {t.objective} | `{t.status}` | {t.priority} | {t.progress}% |")
            lines.append("")
            lines.append("---")
            lines.append("*ContextPilot AI — Verified Agentic Execution*")
            output_text = "\n".join(lines)

        return {
            "success": True,
            "filename": filename,
            "format": export_format,
            "content": output_text,
            "size_bytes": len(output_text.encode("utf-8"))
        }
